import assert from 'node:assert/strict'

// Runs against the isolated in-memory API, never a school database or mail server.
export async function runEnrollmentAdminSmoke({navigate: navigatePage, evaluate, until, screenshot, command, fixture, errors}) {
  const navigate = async (route, text) => {
    const origin = await evaluate('performance.timeOrigin')
    await navigatePage(route, text)
    await until(`performance.timeOrigin !== ${origin} && document.body.innerText.includes(${JSON.stringify(text)})`)
  }
  const click = text => evaluate(`(()=>{const b=[...document.querySelectorAll('button,a')].find(b=>b.textContent.trim()===${JSON.stringify(text)} && b.getClientRects().length);if(!b)throw Error('Missing button: '+${JSON.stringify(text)});b.click()})()`)
  const fill = (selector, value) => evaluate(`(()=>{const e=document.querySelector(${JSON.stringify(selector)});if(!e)throw Error('Missing input');Object.getOwnPropertyDescriptor(Object.getPrototypeOf(e),'value').set.call(e,${JSON.stringify(value)});e.dispatchEvent(new Event(e.tagName==='SELECT'?'change':'input',{bubbles:true}))})()`)
  const fits = async () => assert.ok(await evaluate('document.documentElement.scrollWidth <= innerWidth + 1'), 'No horizontal document overflow')
  await navigate('/admisiones/solicitudes', 'Matrículas')
  await until(`document.body.innerText.includes('MAT-PRUEBA')`)
  assert.equal(await evaluate(`document.querySelectorAll('.intake-tabs button').length`), 5)
  assert.equal(await evaluate(`document.querySelector('a[href="/ingreso"]')?.target`), '_blank')
  await screenshot('intake-admin-desktop', true)
  await click('Nueva convocatoria')
  await until(`location.pathname.endsWith('/convocatorias/nueva') && !!document.querySelector('#campaign-name')`)
  assert.equal(await evaluate(`document.querySelectorAll('[role="dialog"]').length`), 0, 'Campaign opens as a page')
  await fill('#campaign-name', 'Convocatoria QA persistida')
  await evaluate(`document.querySelector('#campaign-no-end').click()`)
  await evaluate(`document.querySelector('#campaign-pin-no-expiry').click()`)
  await evaluate(`document.querySelector('.campaign-grades input[type="checkbox"]').click()`)
  await screenshot('intake-campaign-page-desktop', true)
  // Existing campaign contains requirements; edit its name and verify a reload.
  await click('Volver a convocatorias')
  await until(`location.pathname.endsWith('/convocatorias')`)
  Object.assign(fixture.app.campana.configuracion.documentos[0], {obligatorio: false, formatos: ['docx'], grados: ['G'.repeat(24)]})
  fixture.app.campana.configuracion.documento_identidad = null
  fixture.app.campana.configuracion.documentos.push(...Array.from({length: 4}, (_, index) => ({key: `prueba_${index}`, nombre: `Constancia ${index + 1}`, instrucciones: 'Adjunta la constancia correspondiente.', obligatorio: false, formatos: ['pdf'], grados: []})))
  await navigate(`/admisiones/convocatorias/${fixture.token}/editar`, 'Configurar convocatoria')
  await until(`!!document.querySelector('#campaign-name')`)
  await click('Formulario')
  await screenshot('campaign-form-alignment-desktop', true)
  assert.ok(await evaluate(`(()=>{const row=document.querySelector('.campaign-extra-field'); return Math.abs(row.querySelector('input').getBoundingClientRect().bottom-row.querySelector('select').getBoundingClientRect().bottom)<2})()`), 'Field name and type inputs align')
  await fill('#campaign-name', 'Convocatoria QA persistida')
  await click('Documentos')
  assert.ok(await evaluate(`!!document.querySelector('#campaign-identity option[value="identidad"]')`), 'Identity selector lists a named document even before its restrictions are configured')
  await fill('#campaign-identity', 'identidad')
  await until(`!!document.querySelector('#campaign-auto-identity')`)
  await evaluate(`document.querySelector('#campaign-auto-identity').click()`)
  assert.equal(await evaluate(`document.querySelector('#campaign-auto-identity').checked`), false)
  await command('Emulation.setDeviceMetricsOverride', {width: 1920, height: 1080, deviceScaleFactor: 1, mobile: false})
  await evaluate(`new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))`)
  assert.equal(await evaluate(`getComputedStyle(document.querySelector('.campaign-document-grid')).gridTemplateColumns.split(' ').length`), 4)
  await screenshot('campaign-document-cards-desktop', true)
  await command('Emulation.setDeviceMetricsOverride', {width: 390, height: 844, deviceScaleFactor: 1, mobile: true})
  await evaluate(`new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))`)
  assert.equal(await evaluate(`getComputedStyle(document.querySelector('.campaign-document-grid')).gridTemplateColumns.split(' ').length`), 1)
  assert.ok(await evaluate(`document.documentElement.scrollWidth <= 391`))
  await screenshot('campaign-document-cards-mobile', true)
  await command('Emulation.setDeviceMetricsOverride', {width: 1440, height: 1000, deviceScaleFactor: 1, mobile: false})
  assert.deepEqual(await evaluate(`[...document.querySelector('[aria-label="Formatos del documento 1"]').querySelectorAll('label')].filter(label => label.querySelector('input').checked).map(label => label.textContent)`), ['PDF', 'JPG', 'PNG', 'Obligatorio'])
  await screenshot('intake-campaign-edit-desktop', true)
  await click('Vista previa del formulario')
  await until(`!!document.querySelector('[role="dialog"]')`)
  await screenshot('intake-form-preview-desktop', true)
  await evaluate(`document.querySelector('[role="dialog"] button[aria-label]').click()`)
  await until(`!document.querySelector('[role="dialog"]')`)
  await click('Guardar convocatoria')
  await until(`location.pathname.endsWith('/convocatorias') && document.body.innerText.includes('Convocatoria QA persistida')`)
  assert.ok(fixture.writes.some(w => w.path.includes('/campanas') && w.data.nombre === 'Convocatoria QA persistida'))
  const saved = fixture.writes.findLast(w => w.path.includes('/campanas'))?.data.configuracion
  assert.equal(saved.documento_identidad, 'identidad')
  assert.equal(saved.verificar_identidad_automaticamente, false)
  assert.equal(saved.documentos[0].obligatorio, true)
  assert.deepEqual(saved.documentos[0].grados, [])
  assert.deepEqual(saved.documentos[0].formatos, ['pdf', 'jpg', 'png'])
  await navigate(`/admisiones/convocatorias/${fixture.token}/editar`, 'Configurar convocatoria')
  await until(`document.querySelector('#campaign-name')?.value === 'Convocatoria QA persistida'`)
  await navigate(`/admisiones/convocatorias/${fixture.token}/reutilizar`, 'Duplicar para el próximo año')
  await until(`document.querySelector('#prepare-copy')?.disabled`)
  await fill('#copy-year', fixture.app.campana.ano_token)
  await until(`!document.querySelector('#prepare-copy').disabled`)
  fixture.catalog.anos.push({token: 'Z'.repeat(24), nombre: '2028'})
  const nextGrade = {...fixture.catalog.grados[0], ano_token: 'Z'.repeat(24), token: 'J'.repeat(24)}
  fixture.app.campana.configuracion.documentos[1].grados = [fixture.catalog.grados[0].token]
  await navigate(`/admisiones/convocatorias/${fixture.token}/reutilizar`, 'Duplicar para el próximo año')
  await until(`!!document.querySelector('#copy-documentos')`)
  await evaluate(`document.querySelector('#copy-documentos').click()`)
  await until(`document.querySelector('#prepare-copy').disabled && document.querySelector('[role="alert"]').textContent.includes('Primero')`)
  await evaluate(`document.querySelector('#copy-documentos').click()`)
  await until(`!document.querySelector('#prepare-copy').disabled`)
  fixture.catalog.grados.push(nextGrade)
  await navigate(`/admisiones/convocatorias/${fixture.token}/reutilizar`, 'Duplicar para el próximo año')
  await until(`!!document.querySelector('#copy-grados')`)
  assert.equal(await evaluate(`document.querySelectorAll('fieldset input:checked').length`), 0)
  await evaluate(`document.querySelector('#copy-grados').click()`)
  await evaluate(`document.querySelector('#copy-documentos').click()`)
  await evaluate(`document.querySelector('#prepare-copy').click()`)
  await until(`!!document.querySelector('#campaign-name')`)
  assert.ok(await evaluate(`document.querySelector('.campaign-grades input[type="checkbox"]').checked`), 'Reuse maps stable grade identifiers')
  await click('Formulario')
  assert.equal(await evaluate(`document.querySelectorAll('.campaign-extra-field').length`), 0)
  await click('Guardar convocatoria')
  await until(`location.pathname.endsWith('/convocatorias')`)
  const copied = fixture.writes.findLast(w => w.path === '/api/ingreso/campanas').data
  assert.equal(copied.ano_token, nextGrade.ano_token)
  assert.equal(copied.abierta, false)
  assert.deepEqual(copied.configuracion.campos, [])
  assert.equal(copied.configuracion.grados[0].token, nextGrade.token)
  assert.equal(copied.configuracion.documento_identidad, 'identidad')
  assert.equal(copied.configuracion.documentos.length, saved.documentos.length)
  assert.deepEqual(copied.configuracion.documentos[1].grados, [nextGrade.token])
  assert.equal(copied.configuracion.pin_expira_en, null)
  assert.ok(fixture.app.campana.configuracion.campos.length > 0)
  await navigate('/admisiones/matriculas', 'Matrículas')
  await until(`document.body.innerText.includes('Ana Pruebas')`)
  await screenshot('intake-enrolled-desktop', true)
  await navigate('/admisiones/notificaciones', 'Matrículas')
  await until(`!!document.querySelector('.intake-tabs')`)
  await screenshot('intake-notices-desktop', true)
  await command('Emulation.setDeviceMetricsOverride', {width: 390, height: 844, deviceScaleFactor: 1, mobile: true})
  await navigate('/admisiones/solicitudes', 'Matrículas')
  await until(`document.body.innerText.includes('MAT-PRUEBA')`)
  await fits()
  await screenshot('intake-admin-mobile', true)
  await click('Ver expediente')
  await until(`document.body.innerText.includes('Siguiente paso')`)
  await fits()
  await screenshot('intake-record-mobile', true)
  await click('Revisar correos')
  await until(`!!document.querySelector('button[aria-pressed="false"]')`)
  await evaluate(`[...document.querySelectorAll('button[aria-pressed]')].find(e=>e.textContent.includes('Ana') && e.textContent.includes('Admisión')).click()`)
  assert.ok(await evaluate(`[...document.querySelectorAll('button')].find(b=>b.textContent==='Autorizar un reenvío').disabled`))
  await fill('textarea[maxlength="1000"]', 'Ana confirmó la admisión.')
  await click('Confirmar que llegó')
  await until(`document.body.innerText.includes('Entrega confirmada · Ana · Admisión')`)
  await fits()
  await navigate('/admisiones/convocatorias/nueva', 'Nueva convocatoria')
  await until(`!!document.querySelector('#campaign-name')`)
  await fits()
  await screenshot('intake-campaign-page-mobile', true)
  assert.deepEqual(errors, [], 'No uncaught browser errors')
  console.log('PASS: enrollment tabs, full-page campaign create/edit/reuse, persistent campaign reload, preview, enrolled students and mobile layout.')
}
