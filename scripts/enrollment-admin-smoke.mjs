import assert from 'node:assert/strict'

// Runs against the isolated in-memory API, never a school database or mail server.
export async function runEnrollmentAdminSmoke({navigate: navigatePage, evaluate, until, screenshot, command, fixture, errors}) {
  const navigate = async (route, text) => {
    const origin = await evaluate('performance.timeOrigin')
    await navigatePage(route, text)
    await until(`performance.timeOrigin !== ${origin} && document.body.innerText.includes(${JSON.stringify(text)})`)
  }
  const click = text => evaluate(`(()=>{const b=[...document.querySelectorAll('button,a')].find(b=>b.textContent.trim()===${JSON.stringify(text)} && b.getClientRects().length);if(!b)throw Error('Missing button: '+${JSON.stringify(text)});b.click()})()`)
  const fill = (selector, value) => evaluate(`(()=>{const e=document.querySelector(${JSON.stringify(selector)});if(!e)throw Error('Missing input');Object.getOwnPropertyDescriptor(Object.getPrototypeOf(e),'value').set.call(e,${JSON.stringify(value)});e.dispatchEvent(new Event(e.tagName==='SELECT'?'change':'input',{bubbles:true}))})()`)
  const fits = async () => assert.ok(await evaluate('document.documentElement.scrollWidth <= innerWidth + 1'), 'No horizontal document overflow')
  await navigate('/admisiones/solicitudes', 'Matrículas')
  await until(`document.body.innerText.includes('MAT-PRUEBA')`)
  assert.equal(await evaluate(`document.querySelectorAll('.intake-tabs button').length`), 5)
  assert.equal(await evaluate(`document.querySelector('a[href="/ingreso"]')?.target`), '_blank')
  await screenshot('intake-admin-desktop', true)
  await click('Nueva convocatoria')
  await until(`location.pathname.endsWith('/convocatorias/nueva') && !!document.querySelector('#campaign-name')`)
  assert.equal(await evaluate(`document.querySelectorAll('[role="dialog"]').length`), 0, 'Campaign opens as a page')
  await fill('#campaign-name', 'Convocatoria QA persistida')
  await evaluate(`document.querySelector('#campaign-no-end').click()`)
  await evaluate(`document.querySelector('#campaign-pin-no-expiry').click()`)
  await evaluate(`document.querySelector('.campaign-grades input[type="checkbox"]').click()`)
  await screenshot('intake-campaign-page-desktop', true)
  // Existing campaign contains requirements; edit its name and verify a reload.
  await click('Volver a convocatorias')
  await until(`location.pathname.endsWith('/convocatorias')`)
  await navigate(`/admisiones/convocatorias/${fixture.token}/editar`, 'Configurar convocatoria')
  await until(`!!document.querySelector('#campaign-name')`)
  await fill('#campaign-name', 'Convocatoria QA persistida')
  await screenshot('intake-campaign-edit-desktop', true)
  await click('Vista previa del formulario')
  await until(`!!document.querySelector('[role="dialog"]')`)
  await screenshot('intake-form-preview-desktop', true)
  await evaluate(`document.querySelector('[role="dialog"] button[aria-label]').click()`)
  await until(`!document.querySelector('[role="dialog"]')`)
  await click('Guardar convocatoria')
  await until(`location.pathname.endsWith('/convocatorias') && document.body.innerText.includes('Convocatoria QA persistida')`)
  assert.ok(fixture.writes.some(w => w.path.includes('/campanas') && w.data.nombre === 'Convocatoria QA persistida'))
  await navigate(`/admisiones/convocatorias/${fixture.token}/editar`, 'Configurar convocatoria')
  await until(`document.querySelector('#campaign-name')?.value === 'Convocatoria QA persistida'`)
  await navigate(`/admisiones/convocatorias/${fixture.token}/reutilizar`, 'Duplicar para el próximo año')
  await until(`!!document.querySelector('#campaign-name')`)
  assert.ok(await evaluate(`document.querySelector('.campaign-grades input[type="checkbox"]').checked`), 'Reuse maps stable grade identifiers')
  await navigate('/admisiones/matriculas', 'Matrículas')
  await until(`document.body.innerText.includes('Ana Pruebas')`)
  await screenshot('intake-enrolled-desktop', true)
  await navigate('/admisiones/notificaciones', 'Matrículas')
  await until(`!!document.querySelector('.intake-tabs')`)
  await screenshot('intake-notices-desktop', true)
  await command('Emulation.setDeviceMetricsOverride', {width: 390, height: 844, deviceScaleFactor: 1, mobile: true})
  await navigate('/admisiones/solicitudes', 'Matrículas')
  await until(`document.body.innerText.includes('MAT-PRUEBA')`)
  await fits()
  await screenshot('intake-admin-mobile', true)
  await click('Ver expediente')
  await until(`document.body.innerText.includes('Siguiente paso')`)
  await fits()
  await screenshot('intake-record-mobile', true)
  await navigate('/admisiones/convocatorias/nueva', 'Nueva convocatoria')
  await until(`!!document.querySelector('#campaign-name')`)
  await fits()
  await screenshot('intake-campaign-page-mobile', true)
  assert.deepEqual(errors, [], 'No uncaught browser errors')
  console.log('PASS: enrollment tabs, full-page campaign create/edit/reuse, persistent campaign reload, preview, enrolled students and mobile layout.')
}
