import assert from 'node:assert/strict'

// Browser contract test with an isolated API; no real student or email is modified.
export async function runEnrollmentWorkflowSmoke({navigate: navigatePage, evaluate, until, screenshot, command, fixture, errors}) {
  const navigate = async (route, text) => {
    const origin = await evaluate('performance.timeOrigin')
    await navigatePage(route, text)
    await until(`performance.timeOrigin !== ${origin} && document.body.innerText.includes(${JSON.stringify(text)})`)
  }
  const click = async (text, scope = 'body') => {
    const target = `[...document.querySelector(${JSON.stringify(scope)})?.querySelectorAll('button,a') ?? []].find(b=>b.textContent.trim()===${JSON.stringify(text)} && b.getClientRects().length && !b.disabled)`
    await until(`!!(${target})`)
    await evaluate(`(${target}).click()`)
  }
  const fill = (selector, value) => evaluate(`(()=>{const e=document.querySelector(${JSON.stringify(selector)});if(!e)throw Error('Missing input: '+${JSON.stringify(selector)});Object.getOwnPropertyDescriptor(Object.getPrototypeOf(e),'value').set.call(e,${JSON.stringify(value)});e.dispatchEvent(new Event(e.tagName==='SELECT'?'change':'input',{bubbles:true}))})()`)
  const record = async () => {
    await navigate('/admisiones/solicitudes', 'Matrículas')
    await until(`document.body.innerText.includes('MAT-PRUEBA')`)
    await click('Ver expediente')
    await until(`document.body.innerText.includes('Siguiente paso')`)
  }
  const formStep = async index => {
    await evaluate(`document.querySelectorAll('.intake-steps button')[${index}].click()`)
    await until(`document.querySelectorAll('.intake-steps button')[${index}].getAttribute('aria-current') === 'step'`)
  }
  const fits = async () => assert.ok(await evaluate('document.documentElement.scrollWidth <= innerWidth + 1'), 'No horizontal document overflow')
  await navigate('/ingreso', 'Solicitar PIN')
  await until(`document.querySelector('img[src="/api/branding/logo"]')?.naturalWidth > 0`)
  await click('Solicitar PIN')
  await until(`!!document.querySelector('#pin-email')`)
  await fill('#intake-primer_nombre', 'Ana')
  await fill('#intake-primer_apellido', 'Pruebas')
  await fill('#intake-identity', '1234567')
  await fill('#pin-email', fixture.app.email)
  await fill('#pin-grade', 'G'.repeat(24))
  await click('Enviar solicitud de PIN')
  await until(`document.body.innerText.includes('Tu solicitud de PIN fue recibida.')`)
  await screenshot('intake-pin-request-desktop', true)
  assert.ok(fixture.writes.some(w => w.path.endsWith('/iniciar')))

  await record()
  await click('Activar y entregar PIN')
  await until(`!!document.querySelector('[role="dialog"] #pin-expiry')`)
  await click('Activar y entregar PIN', '[role="dialog"]')
  await until(`document.querySelector('[role="dialog"]')?.innerText.includes('12345678')`)
  await screenshot('intake-pin-delivery-desktop', true)
  await click('Cerrar', '[role="dialog"]')
  assert.equal(fixture.app.estado, 'borrador')

  await navigate('/ingreso', 'Ya tengo un PIN')
  await click('Ya tengo un PIN')
  await until(`!!document.querySelector('#access-pin')`)
  await fill('#intake-identity', '1234567')
  await fill('#access-pin', '12345678')
  await click('Ingresar')
  await until(`!!document.querySelector('.intake-steps')`)
  await fill('#intake-segundo_nombre', 'María')
  await click('Guardar avance')
  await until(`[...document.querySelectorAll('button')].some(b => b.textContent.trim() === 'Guardar avance' && !b.disabled)`)
  await navigate('/ingreso', 'Formulario de inscripción')
  await until(`document.querySelector('#intake-segundo_nombre')?.value === 'María'`)
  await screenshot('intake-public-form-desktop', true)
  await formStep(5)
  await evaluate(`document.querySelector('input[type="checkbox"][required]').click()`)
  await click('Enviar inscripción')
  await until(`!document.querySelector('.intake-steps') && document.body.innerText.includes('Estado de la inscripción')`)
  assert.equal(fixture.app.estado, 'enviada')

  await record()
  await evaluate(`document.querySelector('button[aria-label="Solicitar corrección Segundo nombre"]').click()`)
  await until(`!!document.querySelector('#correction-reason')`)
  await fill('#correction-reason', 'Revisa el segundo nombre contra el documento de identidad.')
  await fill('#correction-deadline', '2027-12-30T18:00')
  await click('Enviar solicitud de corrección', '[role="dialog"]')
  await until(`!document.querySelector('[role="dialog"]')`)
  assert.equal(fixture.app.estado, 'correcciones')
  await navigate('/ingreso', 'Corregir inscripción')
  await click('Corregir inscripción')
  await until(`!!document.querySelector('#intake-segundo_nombre')`)
  assert.equal(await evaluate(`document.querySelector('#intake-primer_nombre').disabled`), true, 'Only requested fields are editable')
  assert.equal(await evaluate(`document.querySelector('#intake-segundo_nombre').disabled`), false)
  await fill('#intake-segundo_nombre', 'Isabel')
  await formStep(5)
  await evaluate(`document.querySelector('input[type="checkbox"][required]').click()`)
  await click('Enviar inscripción')
  await until(`!document.querySelector('.intake-steps')`)
  assert.equal(fixture.app.datos.segundo_nombre, 'Isabel')
  assert.equal(fixture.app.estado, 'enviada')

  await record()
  assert.equal(await evaluate(`[...document.querySelectorAll('button')].some(b=>b.textContent.trim()==='Admitir estudiante' && !b.disabled)`), false, 'Validation precedes admission')
  await click('Documentos')
  await click('Aprobar documento')
  await until(`document.body.innerText.includes('Aprobado')`)
  await click('Validar documentación')
  await until(`document.body.innerText.includes('Admitir estudiante')`)
  assert.equal(fixture.app.estado, 'validada')
  await click('Admitir estudiante')
  await until(`!!document.querySelector('#decision-reason')`)
  await fill('#decision-reason', 'Admisión de prueba tras validar el expediente.')
  await click('Confirmar', '[role="dialog"]')
  await until(`!!document.querySelector('#enroll-group')`)
  assert.equal(fixture.app.estado, 'aprobada')
  await fill('#enroll-group', 'Q'.repeat(24))
  await click('Confirmar matrícula')
  await until(`!!document.querySelector('[role="dialog"]')`)
  await click('Confirmar', '[role="dialog"]')
  await until(`!document.querySelector('[role="dialog"]') && !document.querySelector('#enroll-group')`)
  assert.equal(fixture.app.estado, 'matriculada')
  await screenshot('intake-enrollment-confirmed-desktop', true)

  await command('Emulation.setDeviceMetricsOverride', {width: 390, height: 844, deviceScaleFactor: 1, mobile: true})
  await navigate('/ingreso', 'Estado de la inscripción')
  await fits()
  await screenshot('intake-public-status-mobile', true)
  await click('Salir')
  await until(`document.body.innerText.includes('Solicitar PIN')`)
  await fits()
  await screenshot('intake-public-portal-mobile', true)
  await command('Emulation.clearDeviceMetricsOverride')
  assert.deepEqual(errors, [], 'No uncaught browser errors')
  console.log('Enrollment workflow passed: PIN, draft reload, submission, selective correction, document validation, admission, enrollment and mobile status.')
}
