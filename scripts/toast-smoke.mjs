import assert from 'node:assert/strict'

export async function runToastSmoke({evaluate,until,command,screenshot,sleep,errors}) {
  const click = kind => evaluate(`document.querySelector('[data-toast-kind="${kind}"]').click()`)
  for(const kind of ['success','updated','warning','danger','info','deleted']) await click(kind)
  await until(`document.querySelectorAll('.app-toast').length === 6`)
  await sleep(250)
  const layout = await evaluate(`(()=>{const region=document.querySelector('.app-toast-region'),r=region.getBoundingClientRect();return {right:innerWidth-r.right,bottom:innerHeight-r.bottom,width:r.width,position:getComputedStyle(region).position,items:[...region.querySelectorAll('.app-toast')].map(e=>({height:e.getBoundingClientRect().height,color:getComputedStyle(e).backgroundColor,buttons:e.querySelectorAll('button').length,icon:e.querySelector('.app-toast-icon svg').getBoundingClientRect().width,bar:e.querySelector('.app-toast-timer').getBoundingClientRect().height}))}})()`)
  assert.equal(layout.position,'fixed');assert.equal(layout.right,20);assert.equal(layout.bottom,20);assert.equal(layout.width,350)
  assert.equal(new Set(layout.items.map(item=>item.color)).size,6,'Each state has its own background.')
  assert.ok(layout.items.every(item=>item.height<=100&&item.buttons===1&&item.icon===20&&item.bar===3),'Only a small icon, message, close control and progress bar are shown.')
  assert.equal(await evaluate(`document.querySelector('.app-toast--danger').getAttribute('role')`),'alert')
  await screenshot('toasts-compact-desktop')
  const point=await evaluate(`(()=>{const r=document.querySelector('.app-toast--success').getBoundingClientRect();return {x:r.left+60,y:r.top+20}})()`)
  await command('Input.dispatchMouseEvent',{type:'mouseMoved',...point})
  await until(`document.querySelector('.app-toast--success').classList.contains('is-paused')`)
  assert.equal(await evaluate(`getComputedStyle(document.querySelector('.app-toast--success .app-toast-timer > span')).animationPlayState`),'paused')
  await evaluate(`new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))`)
  const width=await evaluate(`document.querySelector('.app-toast--success .app-toast-timer > span').getBoundingClientRect().width`)
  await sleep(600)
  assert.ok(Math.abs(width-await evaluate(`document.querySelector('.app-toast--success .app-toast-timer > span').getBoundingClientRect().width`))<1,'Hover pauses the visible countdown.')
  await until(`document.querySelectorAll('.app-toast').length === 1`)
  assert.ok(await evaluate(`!!document.querySelector('.app-toast--success')`),'Hover also pauses expiry while the other notices expire.')
  await evaluate(`document.querySelector('.app-toast-close').focus()`)
  await command('Input.dispatchMouseEvent',{type:'mouseMoved',x:100,y:100})
  await sleep(300)
  assert.ok(await evaluate(`document.querySelector('.app-toast').classList.contains('is-paused')`),'Keyboard focus keeps the notification available.')
  await evaluate(`document.activeElement.blur()`)
  await until(`document.querySelectorAll('.app-toast').length === 0`)
  await click('warning')
  await evaluate(`document.querySelector('.app-toast-close').click()`)
  assert.equal(await evaluate(`document.querySelectorAll('.app-toast').length`),0,'Manual close removes the notice.')
  await evaluate(`document.querySelector('#toast-escaped').click()`)
  assert.equal(await evaluate(`document.querySelector('.app-toast-message b')`),null,'Messages stay plain text.')
  await evaluate(`document.querySelector('.app-toast-close').click()`)
  for(const width of [390,320]) {
    await command('Emulation.setDeviceMetricsOverride',{width,height:844,deviceScaleFactor:1,mobile:true})
    await click('danger');await click('updated');await evaluate(`document.querySelector('#toast-long').click()`)
    await sleep(250)
    assert.ok(await evaluate(`(()=>{const r=document.querySelector('.app-toast-region').getBoundingClientRect();return r.left>=12 && r.right<=innerWidth-12 && innerHeight-r.bottom===12 && document.documentElement.scrollWidth<=innerWidth})()`),'Mobile notices stay inside the viewport.')
    if(width===390) await screenshot('toasts-compact-mobile')
    await evaluate(`document.querySelectorAll('.app-toast-close').forEach(e=>e.click())`)
  }
  await evaluate(`(()=>{const e=document.querySelector('select');e.value='en';e.dispatchEvent(new Event('change',{bubbles:true}))})()`)
  await click('info')
  await until(`!!document.querySelector('.app-toast-close[aria-label="Dismiss notification"]')`)
  await evaluate(`document.documentElement.dataset.bsTheme='dark'`)
  assert.equal(await evaluate(`getComputedStyle(document.querySelector('.app-toast')).backgroundColor`),'rgb(32, 37, 50)')
  await sleep(200);await screenshot('toasts-compact-dark')
  await evaluate(`document.querySelectorAll('.app-toast-close').forEach(e=>e.click())`)
  assert.deepEqual(errors,[])
  console.log('PASS: six compact states, bottom-right placement, timed progress, hover/focus pause, close, plain-text messages, mobile, dark mode and i18n.')
}
