import assert from 'node:assert/strict'

export function commercialFixture() {
  const rates = {asistencia: 200, preinformes: 200, boletines_personalizables: 300, aula: 300, soporte_prioritario: 100}
  const base = ['nucleo', 'academico', 'comunicacion_basica', 'boletines_predefinidos']
  const data = ['estandar','premium'].map(key => ({key, name: key === 'premium' ? 'Premium' : 'Estándar', is_active: true,
    storage_gb: key === 'premium' ? 5 : 2, max_sedes: key === 'premium' ? 3 : 1, max_estudiantes: null,
    max_roles_personalizados: null, features: key === 'premium' ? [...base, ...Object.keys(rates)] : base,
    pricing: {currency: 'COP', student_monthly: key === 'premium' ? 2500 : 1500, minimum_students: 30,
      included_sites: key === 'premium' ? 3 : 1, additional_site_monthly: 15000, addons: rates}}))
  const catalog = {features: [...base,...Object.keys(rates)].map(key => ({key, label: `plan.f.${({nucleo:'nucleo',academico:'academico',comunicacion_basica:'comunicacionBasica',boletines_predefinidos:'presets',asistencia:'asistencia',preinformes:'preinformes',boletines_personalizables:'boletines',aula:'aula',soporte_prioritario:'soportePrioritario'})[key] ?? 'academico'}`, description:'plan.f.academico.desc', available: true})), limits: []}
  catalog.features = catalog.features.map(feature=>({...feature,description:feature.label+'.desc'}))
  catalog.features.push({key:'simat',label:'plan.f.simat',description:'plan.f.simat.desc',available:false})
  const requests = []
  return {requests, middleware(req,res,next) {
    const url = new URL(req.url,'http://localhost')
    if (!url.pathname.startsWith('/api/plans') && url.pathname !== '/api/subscription/offers') return next()
    requests.push({method:req.method,path:url.pathname})
    res.setHeader('Content-Type','application/json')
    if (url.pathname === '/api/plans/offers' || url.pathname === '/api/subscription/offers') {
      res.end(JSON.stringify({data:data.map(plan=>{const students=Number(url.searchParams.get('students')??30),sites=Number(url.searchParams.get('sites')??1),extra=Math.max(0,sites-plan.pricing.included_sites);return {...plan,quote:{students,sites,student_monthly:plan.pricing.student_monthly,students_total:students*plan.pricing.student_monthly,addon_lines:[],additional_sites:extra,sites_total:extra*15000,monthly_total:students*plan.pricing.student_monthly+extra*15000}}}),catalog,current:null}));return
    }
    if (req.method === 'GET') {res.end(JSON.stringify({data,catalog})); return}
    let raw = ''; req.on('data',chunk => {raw += chunk}); req.on('end',() => {
      const input = JSON.parse(raw)
      if (req.method === 'PUT') {
        const plan = data.find(row=>url.pathname === '/api/plans/'+row.key)
        Object.assign(plan,input); res.end(JSON.stringify({plan}));return
      }
      if (url.pathname === '/api/plans/quote') {
        const contract = input.subscription, rule = {...data.find(row => row.key === input.plan).pricing,...(contract.customized?contract.pricing_override??{}:{})}
        const students = Math.max(30,contract.students), extra = Math.max(0,contract.sites-rule.included_sites)
        const addon_lines = contract.addons.map(key => ({key,unit:rates[key],quantity:students,total:rates[key]*students}))
        const total = students*rule.student_monthly + addon_lines.reduce((sum,line)=>sum+line.total,0)+extra*rule.additional_site_monthly
        const discount_total = Math.round(total*(contract.discount_percent ?? 0)/100)
        setTimeout(() => res.end(JSON.stringify({quote:{subtotal:total,discount_percent:contract.discount_percent ?? 0,discount_total,annual_reference:12*(total-discount_total),students,sites:contract.sites,base_student_monthly:rule.student_monthly,
          students_total:students*rule.student_monthly, addon_lines, additional_sites:extra, sites_total:extra*rule.additional_site_monthly, monthly_total:total-discount_total}})), 200)
      } else res.end('{}')
    })
  }}
}

